import Foundation

enum CaptureDecision: Equatable {
  case keep
  case ignore(CaptureIgnoreReason)
}

enum CaptureIgnoreReason: String, Equatable {
  case paused
  case empty
  case unsupported
  case concealed
  case transient
  case ignoredType
  case ignoredApp
  case oversized
  case ownWrite
}

enum CapturePolicy {
  static let maxEntryBytes = 2 * 1024 * 1024

  static let concealedMarkers: Set<String> = [
    "org.nspasteboard.ConcealedType",
    "com.agilebits.onepassword",
    "net.antelle.keeweb"
  ]

  static let transientMarkers: Set<String> = [
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "de.petermaurer.TransientPasteboardType"
  ]

  static func decide(
    types: Set<String>,
    enabledTypes: Set<String>,
    ignoredTypes: Set<String>,
    sourceBundleID: String?,
    ignoredApps: [String],
    ignoreAllAppsExceptListed: Bool,
    stringIsEmpty: Bool,
    hasRichText: Bool,
    byteCount: Int,
    recordingPaused: Bool,
    isOwnWrite: Bool
  ) -> CaptureDecision {
    if isOwnWrite { return .ignore(.ownWrite) }
    if recordingPaused { return .ignore(.paused) }
    if byteCount > maxEntryBytes { return .ignore(.oversized) }

    if !types.isDisjoint(with: concealedMarkers) || !types.isDisjoint(with: ignoredTypes.intersection(concealedMarkers)) {
      return .ignore(.concealed)
    }
    if !types.isDisjoint(with: transientMarkers) {
      return .ignore(.transient)
    }
    if !types.isDisjoint(with: ignoredTypes) {
      return .ignore(.ignoredType)
    }

    if let sourceBundleID {
      if ignoreAllAppsExceptListed {
        if !ignoredApps.contains(sourceBundleID) { return .ignore(.ignoredApp) }
      } else if ignoredApps.contains(sourceBundleID) {
        return .ignore(.ignoredApp)
      }
    }

    let usable = types.intersection(enabledTypes).filter { type in
      !type.hasPrefix("dyn.") && !type.hasPrefix("com.microsoft.ole.source.")
    }
    if usable.isEmpty { return .ignore(.unsupported) }
    if stringIsEmpty && !hasRichText { return .ignore(.empty) }
    return .keep
  }
}
